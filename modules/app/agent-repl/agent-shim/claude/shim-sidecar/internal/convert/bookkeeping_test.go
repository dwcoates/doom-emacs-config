func TestUnmodelledNonHumanOriginIsUnknownResidueNeverAPrompt(t *testing.T) {
	// Arrange. An origin kind that names no person and no modelled source.
	c := newTestConverter(t)
	line := `{"type":"user","uuid":"u1","isSidechain":false,"entrypoint":"cli","origin":{"kind":"scheduler"},"timestamp":"` + ts1 +
		`","message":{"role":"user","content":"wake up"}}`

	// Act.
	entries := convertLines(t, c, line)

	// Assert.
	if rows := promptRows(entries); len(rows) != 0 {
		t.Fatalf("minted %d prompt row(s) for a non-human origin", len(rows))
	}
	unknown := entries[0].GetAgentUpdate().GetUnservedItem().GetUnknown()
	if unknown.GetDiscriminatorField() != "origin.kind" || unknown.GetDiscriminator() != "scheduler" {
		t.Fatalf("unknown = %v, want origin.kind=scheduler", unknown)
	}
}
