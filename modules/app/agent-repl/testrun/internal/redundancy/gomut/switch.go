package gomut

// switchSource is the file a schema adds to the mutated package: the active
// mutant, read once from the environment, and the helpers every site calls.
// With no mutant active each helper computes exactly the original expression.
const switchSource = `// Code generated by testrun redundancy (gomut); it exists only in an overlay.

package PACKAGE

import (
	"cmp"
	"os"
	"strconv"
)

var agentReplMutantActive = agentReplMutantFromEnv()

func agentReplMutantFromEnv() int {
	s := os.Getenv("` + EnvMutant + `")
	if s == "" {
		return 0
	}
	n, err := strconv.Atoi(s)
	if err != nil || n < 1 {
		panic("` + EnvMutant + `=" + s + " is not a mutant id")
	}
	return n
}

func agentReplMutOn(id int) bool { return agentReplMutantActive == id }

func agentReplMutFlip(id int, b bool) bool { return b != (agentReplMutantActive == id) }

func agentReplMutCmp[T cmp.Ordered](boundary, negate int, op string, a, b T) bool {
	var r bool
	switch op {
	case "<":
		r = a < b
		if agentReplMutantActive == boundary {
			r = a <= b
		}
	case "<=":
		r = a <= b
		if agentReplMutantActive == boundary {
			r = a < b
		}
	case ">":
		r = a > b
		if agentReplMutantActive == boundary {
			r = a >= b
		}
	case ">=":
		r = a >= b
		if agentReplMutantActive == boundary {
			r = a > b
		}
	default:
		panic("agentReplMutCmp: operator " + op)
	}
	return r != (agentReplMutantActive == negate)
}

func agentReplMutLogic(id int, and bool, x, y func() bool) bool {
	if and != (agentReplMutantActive == id) {
		return x() && y()
	}
	return x() || y()
}

type agentReplMutNumber interface {
	~int | ~int8 | ~int16 | ~int32 | ~int64 |
		~uint | ~uint8 | ~uint16 | ~uint32 | ~uint64 | ~uintptr |
		~float32 | ~float64
}

type agentReplMutInteger interface {
	~int | ~int8 | ~int16 | ~int32 | ~int64 |
		~uint | ~uint8 | ~uint16 | ~uint32 | ~uint64 | ~uintptr
}

func agentReplMutArith[T agentReplMutNumber](id int, op string, a, b T) T {
	on := agentReplMutantActive == id
	switch op {
	case "+":
		if on {
			return a - b
		}
		return a + b
	case "-":
		if on {
			return a + b
		}
		return a - b
	case "*":
		if on {
			return a / b
		}
		return a * b
	case "/":
		if on {
			return a * b
		}
		return a / b
	}
	panic("agentReplMutArith: operator " + op)
}

func agentReplMutRem[T agentReplMutInteger](id int, op string, a, b T) T {
	if agentReplMutantActive == id {
		return a * b
	}
	return a % b
}

func agentReplMutNilErr(id int, err error) error {
	if agentReplMutantActive == id {
		return nil
	}
	return err
}
`
