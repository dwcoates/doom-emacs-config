// bindingSet is a descriptor set of one file, x/v1/x.proto: message Outer
// holding a field of message Held and a nested Inner, an unrelated message
// Other, an enum Mode and a service Svc whose method takes Held.
func bindingSet(heldFields ...string) *descriptorpb.FileDescriptorSet {
	held := &descriptorpb.DescriptorProto{Name: proto.String("Held")}
	for i, f := range heldFields {
		held.Field = append(held.Field, &descriptorpb.FieldDescriptorProto{Name: proto.String(f), Number: proto.Int32(int32(i + 1)),
			Type: descriptorpb.FieldDescriptorProto_TYPE_STRING.Enum()})
	}
	return &descriptorpb.FileDescriptorSet{File: []*descriptorpb.FileDescriptorProto{{
		Name: proto.String("x/v1/x.proto"), Package: proto.String("x.v1"),
		MessageType: []*descriptorpb.DescriptorProto{
			{Name: proto.String("Outer"), Field: []*descriptorpb.FieldDescriptorProto{{Name: proto.String("held"), Number: proto.Int32(1),
				Type: descriptorpb.FieldDescriptorProto_TYPE_MESSAGE.Enum(), TypeName: proto.String(".x.v1.Held")}},
				NestedType: []*descriptorpb.DescriptorProto{{Name: proto.String("Inner")}}},
			held,
			{Name: proto.String("Other")},
		},
		EnumType: []*descriptorpb.EnumDescriptorProto{{Name: proto.String("Mode"), Value: []*descriptorpb.EnumValueDescriptorProto{{Name: proto.String("MODE_ON"), Number: proto.Int32(0)}}}},
		Service: []*descriptorpb.ServiceDescriptorProto{{Name: proto.String("Svc"), Method: []*descriptorpb.MethodDescriptorProto{{
			Name: proto.String("Do"), InputType: proto.String(".x.v1.Held"), OutputType: proto.String(".x.v1.Other")}}}},
	}}}
}

func mustBindings(t *testing.T, set *descriptorpb.FileDescriptorSet) *Bindings {
	t.Helper()
	b, err := NewBindings([]string{"gen/"}, set)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// reached is the full names TEXT reaches through B.
func reached(b *Bindings, text string) map[string]bool {
	out := map[string]bool{}
	ids, _ := b.Named([]byte(text))
	for full := range b.Fingerprints(ids) {
		out[full] = true
	}
	return out
}

func TestBindingsNamed(t *testing.T) {
	tests := []struct {
		name string
		text string
		want []string
		not  []string
	}{
		{name: "a Go type name reaches it and what it holds", text: "var o *xv1.Outer", want: []string{"x.v1.Outer", "x.v1.Held", "x.v1.Outer.Inner"}, not: []string{"x.v1.Other"}},
		{name: "a oneof arm or nested type reaches its message", text: "x := &xv1.Outer_Inner{}", want: []string{"x.v1.Outer"}},
		{name: "a TypeScript schema reaches its message", text: "create(OtherSchema, {})", want: []string{"x.v1.Other"}, not: []string{"x.v1.Outer"}},
		{name: "an enum value reaches its enum", text: "m := xv1.Mode_MODE_ON", want: []string{"x.v1.Mode"}},
		{name: "a service client reaches its request and response", text: "xv1connect.NewSvcClient(h, u)", want: []string{"x.v1.Svc", "x.v1.Held", "x.v1.Other"}},
		{name: "the file's own descriptor reaches all it declares", text: "xv1.File_x_v1_x_proto", want: []string{"x.v1.Outer", "x.v1.Other", "x.v1.Mode", "x.v1.Svc"}},
		{name: "an identifier only containing a name reaches nothing", text: "var OuterSpace, xOther int", not: []string{"x.v1.Outer", "x.v1.Other"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Arrange
			b := mustBindings(t, bindingSet("id"))

			// Act
			got := reached(b, tt.text)

			// Assert
			for _, w := range tt.want {
				if !got[w] {
					t.Errorf("%q reaches %v, want %s among them", tt.text, got, w)
				}
			}
			for _, n := range tt.not {
				if got[n] {
					t.Errorf("%q reaches %v, want %s not among them", tt.text, got, n)
				}
			}
		})
	}
}

