// bindingTree is a checkout with generated code gen/x.pb.go and a source
// src/use.go naming SOURCE's symbols, keyed as one tree each.
func bindingTree(t *testing.T, source string) (string, *InputSet) {
	t.Helper()
	root := writeTree(t, map[string]string{
		"gen/x.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.11\n// \tprotoc        v6.33.0\npackage xv1\n",
		"src/use.go":  source,
	})
	set := NewInputSet()
	for _, err := range []error{set.AddTree("gen"), set.AddTree("src")} {
		if err != nil {
			t.Fatal(err)
		}
	}
	return root, set
}

func bindingKey(t *testing.T, root string, set *InputSet, b *Bindings) Key {
	t.Helper()
	k, err := ComputeKeyCached(root, set, Facts{}, KeyEnv{Bindings: b})
	if err != nil {
		t.Fatal(err)
	}
	return k
}

func TestAKeyReadsGeneratedCodeByItsSymbols(t *testing.T) {
	tests := []struct {
		name     string
		change   func(t *testing.T, root string) *Bindings
		wantMove bool
	}{
		{name: "a comment in the generated code moves nothing", change: func(t *testing.T, root string) *Bindings {
			write(t, root, "gen/x.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.11\n// \tprotoc        v6.33.0\n// a new comment\npackage xv1\n")
			return mustBindings(t, bindingSet("id"))
		}},
		{name: "a change to a symbol the source never reaches moves nothing", change: func(t *testing.T, root string) *Bindings {
			set := bindingSet("id")
			set.File[0].MessageType[2].Field = []*descriptorpb.FieldDescriptorProto{{Name: proto.String("added"), Number: proto.Int32(1), Type: descriptorpb.FieldDescriptorProto_TYPE_BOOL.Enum()}}
			return mustBindings(t, set)
		}},
		{name: "a field added to a symbol the source reaches moves the key", wantMove: true, change: func(t *testing.T, root string) *Bindings {
			return mustBindings(t, bindingSet("id", "added"))
		}},
		{name: "a new generator moves the key", wantMove: true, change: func(t *testing.T, root string) *Bindings {
			write(t, root, "gen/x.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.37.0\n// \tprotoc        v6.33.0\npackage xv1\n")
			return mustBindings(t, bindingSet("id"))
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Arrange: the source reaches Outer, and so Held.
			root, set := bindingTree(t, "package src\nvar o *xv1.Outer\n")
			before := bindingKey(t, root, set, mustBindings(t, bindingSet("id")))

			// Act
			after := bindingKey(t, root, set, tt.change(t, root))

			// Assert
			if moved := after.Digest != before.Digest; moved != tt.wantMove {
				t.Fatalf("key moved = %v, want %v (changed: %v)", moved, tt.wantMove, after.Manifest.Changed(before.Manifest))
			}
		})
	}
}

func TestAKeyThatReadsNoGeneratedCodeHoldsNoSymbols(t *testing.T) {
	// Arrange: the source names Outer, but the set reads no generated code.
	root := writeTree(t, map[string]string{"src/use.go": "package src\nvar o *xv1.Outer\n"})
	set := NewInputSet()
	if err := set.AddTree("src"); err != nil {
		t.Fatal(err)
	}

	// Act
	k := bindingKey(t, root, set, mustBindings(t, bindingSet("id")))

	// Assert
	for name := range k.Manifest {
		if len(name) > 6 && name[:6] == "@proto" {
			t.Fatalf("manifest holds %s, want no symbols for a key that reads no generated code", name)
		}
	}
}

func TestAKeyWithNoBindingsHashesGeneratedCodeByItsBytes(t *testing.T) {
	// Arrange
	root, set := bindingTree(t, "package src\n")
	before := bindingKey(t, root, set, nil)

	// Act
	write(t, root, "gen/x.pb.go", "// a new comment\npackage xv1\n")
	after := bindingKey(t, root, set, nil)

	// Assert
	if after.Digest == before.Digest {
		t.Fatal("a key with no bindings did not move on a generated file's bytes")
	}
}

func TestExecBindingsIndexesTheProtoSources(t *testing.T) {
	// Arrange: one .proto under MODULE/proto/src.
	repo := writeTree(t, map[string]string{"m/proto/src/x/v1/x.proto": "syntax = \"proto3\";\npackage x.v1;\nmessage Outer { string id = 1; }\n"})
	if _, err := os.Stat(filepath.Join(repo, "m/proto/src/x/v1/x.proto")); err != nil {
		t.Fatal(err)
	}

	// Act
	b, err := ExecBindings(repo, filepath.Join(repo, "m"))

	// Assert
	if err != nil {
		t.Fatalf("ExecBindings: %v", err)
	}
	if !b.Bound("m/proto/gen/go/x/v1/x.pb.go") || b.Bound("m/proto/src/x/v1/x.proto") {
		t.Fatalf("roots %v, want m/proto/gen/ bound and the sources not", b.Roots)
	}
	if got := reached(b, "xv1.Outer"); !got["x.v1.Outer"] {
		t.Fatalf("reached %v, want x.v1.Outer", got)
	}
}

func TestARegistryWalkReachesWhatItsUnitLinks(t *testing.T) {
	tests := []struct {
		name    string
		reads   bool
		wantAll bool
	}{
		{name: "a walk in a unit that reads the generated file reaches its symbols", reads: true, wantAll: true},
		{name: "a walk in a unit that reads no generated file reaches nothing"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Arrange: the source walks the registry and names nothing.
			files := map[string]string{"src/use.go": "package src\nvar _ = protoregistry.GlobalFiles\n"}
			if tt.reads {
				files["gen/go/x/v1/x.pb.go"] = "package xv1\n"
			}
			root := writeTree(t, files)
			set := NewInputSet()
			if err := set.AddTree("src"); err != nil {
				t.Fatal(err)
			}
			if tt.reads {
				if err := set.AddTree("gen"); err != nil {
					t.Fatal(err)
				}
			}

			// Act
			k := bindingKey(t, root, set, mustBindings(t, bindingSet("id")))

			// Assert
			_, outer := k.Manifest["@proto x.v1.Outer"]
			_, other := k.Manifest["@proto x.v1.Other"]
			if (outer && other) != tt.wantAll {
				t.Fatalf("manifest holds Outer %v, Other %v; want every linked symbol %v", outer, other, tt.wantAll)
			}
		})
	}
}

func TestLinkedMapsAGeneratedFileToItsProto(t *testing.T) {
	tests := map[string]bool{
		"gen/go/x/v1/x.pb.go":                 true,
		"gen/go/x/v1/xv1connect/x.connect.go": true,
		"gen/ts/x/v1/x_pb.ts":                 true,
		"gen/go/go.mod":                       false,
		"src/x.go":                            false,
	}
	for gen, want := range tests {
		t.Run(gen, func(t *testing.T) {
			// Arrange
			b := mustBindings(t, bindingSet("id"))

			// Act
			got := len(b.Linked(gen)) > 0

			// Assert
			if got != want {
				t.Fatalf("Linked(%q) found %v, want %v", gen, got, want)
			}
		})
	}
}
